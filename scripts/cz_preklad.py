# od najdlhších, aby sa kratšia fráza nevložila do dlhšej
PAIRS.sort(key=lambda p: -len(p[0]))
_LET = 'A-Za-z0-9À-ž'
_RX = [(re.compile('(?<![' + _LET + '])' + re.escape(a) + '(?![' + _LET + '])'), b) for a, b in PAIRS if a != b]


def preloz(text):
    for rx, b in _RX:
        text = rx.sub(b.replace('\\', '\\\\'), text)
    return text


# slovenské písmená, ktoré čeština nemá – pomôcka na nájdenie nepreložených textov
_SK_ONLY = re.compile('[ľĺŕäôĽĹŔÄÔ]')
def zvysky(text):
    """riadky s typicky slovenskými písmenami (na kontrolu, čo ešte ostalo po slovensky)"""
    return [l.strip() for l in text.split('\n') if _SK_ONLY.search(l)]
